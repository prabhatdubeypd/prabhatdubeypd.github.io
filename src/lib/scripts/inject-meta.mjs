// Writes the link-preview tags into index.html from the Supabase table `site_meta`.
// Runs automatically before every `npm run build`.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const root = process.cwd();

// local builds: read the keys from .env.local (on GitHub they come from secrets)
function loadEnv() {
  for (const f of [".env.local", ".env"]) {
    const p = resolve(root, f);
    if (!existsSync(p)) continue;
    for (const line of readFileSync(p, "utf8").split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*(.*?)\s*$/);
      if (m && !(m[1] in process.env)) process.env[m[1]] = m[2].replace(/^['"]|['"]$/g, "");
    }
  }
}
loadEnv();

const SB = process.env.VITE_SUPABASE_URL;
const KEY = process.env.VITE_SUPABASE_ANON_KEY;

const FALLBACK = {
  site_url: "https://prabhatdubey.github.io",
  site_name: "Prabhat Kumar Dubey",
  title_en: "Prabhat Kumar Dubey | Portfolio",
  description_en: "Portfolio of Prabhat Kumar Dubey, Flutter and Android developer. Explore my work and get in touch.",
  og_image_url: "/og-image.png",
  og_image_alt: "Prabhat Kumar Dubey portfolio preview",
  favicon_emoji: "📖",
  theme_color_light: "#f4f4f0",
  theme_color_dark: "#09090b",
  job_title: "Flutter & Android Developer",
};

const esc = (s) =>
  String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

async function get(path) {
  const r = await fetch(`${SB}/rest/v1/${path}`, { headers: { apikey: KEY, Authorization: `Bearer ${KEY}` } });
  if (!r.ok) throw new Error(`${path} -> ${r.status}`);
  return r.json();
}

let m = { ...FALLBACK };
let links = [];
try {
  if (SB && KEY) {
    const [rows, items] = await Promise.all([
      get("site_meta?id=eq.1&select=*"),
      get("card_items?kind=eq.link&select=url,visible"),
    ]);
    if (rows[0]) {
      const clean = Object.fromEntries(Object.entries(rows[0]).filter(([, v]) => v !== null && v !== ""));
      m = { ...FALLBACK, ...clean };
    }
    links = items.filter((x) => x.visible !== false && x.url).map((x) => x.url);
  } else {
    console.warn("[meta] Supabase keys not found, using the built-in defaults");
  }
} catch (e) {
  console.warn("[meta] could not reach Supabase, using the built-in defaults:", e.message);
}

const site = String(m.site_url).replace(/\/+$/, "");
const abs = (u) => (/^https?:\/\//i.test(u) ? u : `${site}/${String(u).replace(/^\/+/, "")}`);
const img = abs(m.og_image_url);
const icon = `data:image/svg+xml,${encodeURIComponent(
  `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 100 100'><text y='.9em' font-size='90'>${m.favicon_emoji}</text></svg>`
)}`;

const person = {
  "@context": "https://schema.org",
  "@type": "Person",
  name: m.site_name,
  url: `${site}/`,
  image: img,
  jobTitle: m.job_title,
  description: m.description_en,
  ...(links.length ? { sameAs: links } : {}),
};

const block = `<!-- META:START (generated by scripts/inject-meta.mjs from the Supabase table site_meta) -->
    <title>${esc(m.title_en)}</title>
    <meta name="description" content="${esc(m.description_en)}" />
    ${m.keywords ? `<meta name="keywords" content="${esc(m.keywords)}" />` : ""}
    <link rel="canonical" href="${site}/" />
    <link rel="icon" href="${icon}" />
    <meta name="theme-color" content="${esc(m.theme_color_light)}" media="(prefers-color-scheme: light)" />
    <meta name="theme-color" content="${esc(m.theme_color_dark)}" media="(prefers-color-scheme: dark)" />
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="${esc(m.site_name)}" />
    <meta property="og:title" content="${esc(m.title_en)}" />
    <meta property="og:description" content="${esc(m.description_en)}" />
    <meta property="og:url" content="${site}/" />
    <meta property="og:image" content="${esc(img)}" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta property="og:image:alt" content="${esc(m.og_image_alt)}" />
    <meta property="og:locale" content="en_IN" />
    <meta name="twitter:card" content="summary_large_image" />
    <meta name="twitter:title" content="${esc(m.title_en)}" />
    <meta name="twitter:description" content="${esc(m.description_en)}" />
    <meta name="twitter:image" content="${esc(img)}" />
    ${m.twitter_site ? `<meta name="twitter:site" content="${esc(m.twitter_site)}" />` : ""}
    <script type="application/ld+json">${JSON.stringify(person).replace(/</g, "\\u003c")}</script>
    <!-- META:END -->`;

const file = resolve(root, "index.html");
let html = readFileSync(file, "utf8");
if (!/<!-- META:START/.test(html) || !/<!-- META:END -->/.test(html)) {
  console.error("[meta] index.html has no META:START / META:END markers. Use the index.html from the guide.");
  process.exit(1);
}
html = html.replace(/<!-- META:START[\s\S]*?<!-- META:END -->/, () => block);
writeFileSync(file, html);

// robots.txt + sitemap.xml (helps Google find the site)
mkdirSync(resolve(root, "public"), { recursive: true });
writeFileSync(resolve(root, "public/robots.txt"), `User-agent: *\nAllow: /\n\nSitemap: ${site}/sitemap.xml\n`);
writeFileSync(
  resolve(root, "public/sitemap.xml"),
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"><url><loc>${site}/</loc><lastmod>${new Date()
    .toISOString()
    .slice(0, 10)}</lastmod></url></urlset>\n`
);

console.log(`[meta] injected: "${m.title_en}" | image: ${img}`);